def apply(scenes: list) -> None:
    for sc in scenes:
        if sc["id"] not in STAGE:
            continue
        st = STAGE[sc["id"]]
        assert len(st["beats"]) == len(sc["beats"]), (sc["id"], len(st["beats"]), len(sc["beats"]))
        sc["type"] = "stage"
        sc["goal"] = st["goal"]
        if st.get("bg"):
            sc["bg"] = st["bg"]
        for b, s in zip(sc["beats"], st["beats"]):
            b.pop("draw", None)
