def bite(key, vid, who, role, intro, subs, why, intent):
    """subs: [(원본 절대 시각, 한국어), ...] — 첫 시각부터 마지막 자막 끝(end)까지 한 구간"""
    credit, title, date, rights = VID[vid]
    a0, b0 = subs[0][0], subs[-1][0]
    a, b = snap(vid, a0, b0)
    pa, pb = max(0, a - 0.6), b + 0.6
    FOOT[key] = {"file": f"{key}.mp4", "url": f"https://www.youtube.com/watch?v={vid}", "start": f"{int(pa // 60)}:{pa % 60:04.1f}",
                 "end": f"{int(pb // 60)}:{pb % 60:04.1f}", "who": who, "rights": rights, "credit": credit, "title": title, "date": date,
                 "_a": pa, "_b": pb, "_vid": vid}
    times = [max(a, t) for t, _ in subs[:-1]] + [b]
    sub = []
    for i, (t, ko) in enumerate(subs[:-1]):
        sub.append({"t": round(times[i] - a, 3), "ko": ko, "en": en_between(vid, times[i], times[i + 1] + 0.05)})
    cut = [{"key": sub[0]["en"], "start": round(a - pa, 2), "end": round(b - pa, 2), "score": 1, "subs": sub}]
    s = {"type": "bite", "insight": True, "label": f"{OP} · {credit}", "who": who, "role": role,
         "clip": {"src": key, "lang": "en", "cuts": [{"find": u["en"], "ko": u["ko"]} for u in sub], **CNBC_VF},
         "show_lower": False, "show_en": False,
         "beats": [{"say": intro}],
         "decide": D("said", "bite", BITE_OVER, why, intent)}
    s["_cut"] = cut
    return s


