def words(vid):
    if vid not in TR:
        TR[vid] = [w for s in json.loads((SRC / f"{vid}.tr.json").read_text(encoding="utf-8")) for w in s["words"]]
    return TR[vid]


def snap(vid, a, b):
    """시각 a~b 안의 첫 단어 시작·마지막 단어 끝으로 맞춤"""
    ws = [w for w in words(vid) if w["s"] >= a - 0.3 and w["e"] <= b + 0.3]
    return ws[0]["s"], ws[-1]["e"]


def en_between(vid, a, b):
    return "".join(w["w"] for w in words(vid) if a - 0.05 <= w["s"] < b - 0.05).strip()


